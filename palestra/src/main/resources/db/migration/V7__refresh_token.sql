-- A COSA SERVE: settima migration: la tabella dei REFRESH TOKEN della API. Il login restituisce due token: un "access token"
-- (JWT, dura 60 minuti, non salvato da nessuna parte) e un "refresh token" (dura giorni) che serve a ottenerne uno nuovo
-- senza rifare il login. A differenza dell'access token, il refresh token si SALVA qui, perché deve poter essere REVOCATO
-- (logout, rotazione, sospetto furto, utente eliminato).
--
-- SICUREZZA: nel database NON c'è il token, ma solo il suo hash SHA-256, come per le password: chi leggesse questa tabella
-- non potrebbe usare i token. Il token in chiaro esiste solo nella risposta al login/rinnovo (e nel client).
-- PARAGONE LARAVEL: la tabella personal_access_tokens di Sanctum (che salva anch'essa l'hash del token).

CREATE TABLE refresh_token (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- ON DELETE CASCADE: eliminando l'utente spariscono anche i suoi refresh token, quindi chi viene eliminato non può
    -- più rinnovare l'accesso. (Per gli abbonamenti invece NON c'è il cascade, di proposito: lo storico non si perde.)
    utente_id   BIGINT                   NOT NULL REFERENCES utente (id) ON DELETE CASCADE,
    token_hash  VARCHAR(64)              NOT NULL UNIQUE,   -- SHA-256 in esadecimale (64 caratteri); UNIQUE = indice di ricerca
    creato_il   TIMESTAMP WITH TIME ZONE NOT NULL,
    scade_il    TIMESTAMP WITH TIME ZONE NOT NULL,
    revocato_il TIMESTAMP WITH TIME ZONE                    -- NULL = ancora utilizzabile; valorizzato = usato (rotazione) o revocato
);

-- Per trovare/revocare in fretta tutti i token di un utente.
CREATE INDEX idx_refresh_token_utente ON refresh_token (utente_id);

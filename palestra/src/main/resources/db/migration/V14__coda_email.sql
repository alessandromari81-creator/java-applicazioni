-- V14: coda delle email da spedire (nel gergo, una «outbox»).
-- Prima l'email partiva subito, dentro la richiesta: la persona aspettava il server di posta e, se non rispondeva, l'email era persa. Ora la richiesta
-- scrive solo una riga qui e un compito programmato (SpedizioneEmailProgrammata) la legge, la spedisce e, se fallisce, riprova con attese crescenti.
--   stato               DA_INVIARE (aspetta il suo turno), IN_CORSO (qualcuno la sta spedendo), FALLITA (tentativi finiti: non si riprova più).
--                       Una email spedita NON resta qui: la riga si cancella appena parte.
--   tentativi           quante volte l'invio è già fallito.
--   prossimo_tentativo  da quando la riga può essere spedita (all'inizio: subito; dopo un errore: più avanti, 1, 2, 4... minuti).
--   in_corso_dal        da quando è IN_CORSO: se il processo si ferma a metà, dopo un po' la riga torna DA_INVIARE e un altro giro la riprende.
--   ultimo_errore       il motivo dell'ultimo fallimento (solo il tipo di errore e un breve messaggio, mai il contenuto dell'email).
-- ATTENZIONE: corpo_html e corpo_testo contengono il LINK con il token vero (nel resto del database c'è solo l'hash). Per questo la riga si cancella appena
-- l'email parte, e le righe FALLITA le cancella la pulizia notturna dopo poche ore: il token vero non deve restare qui.
CREATE TABLE email_in_coda (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destinatario        VARCHAR(255)             NOT NULL,
    oggetto             VARCHAR(255)             NOT NULL,
    corpo_html          TEXT                     NOT NULL,
    corpo_testo         TEXT                     NOT NULL,
    stato               VARCHAR(20)              NOT NULL DEFAULT 'DA_INVIARE' CHECK (stato IN ('DA_INVIARE', 'IN_CORSO', 'FALLITA')),
    tentativi           INTEGER                  NOT NULL DEFAULT 0,
    prossimo_tentativo  TIMESTAMP WITH TIME ZONE NOT NULL,
    in_corso_dal        TIMESTAMP WITH TIME ZONE,
    ultimo_errore       VARCHAR(255),
    creata_il           TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Serve alla ricerca del prossimo gruppo da spedire: «stato = DA_INVIARE e prossimo_tentativo già passato».
CREATE INDEX idx_email_in_coda_da_spedire ON email_in_coda (stato, prossimo_tentativo);

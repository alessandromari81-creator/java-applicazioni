-- FILE: V3__crea_amministratore.sql
-- A COSA SERVE: terza migration: crea la tabella degli amministratori, cioè chi può fare login nel pannello.
-- Prima l'unico admin stava in memoria, con la password in application.properties.
-- PARAGONE LARAVEL: la tabella "users" (con la colonna password).
-- Le migration V1 e V2 sono già applicate e non si toccano: per aggiungere cose si crea un NUOVO file, come questo.
--
-- La tabella resta VUOTA: il primo amministratore lo crea l'applicazione all'avvio (classe AdminIniziale),
-- così nessuna password o hash è scritta in questo file e finisce nel repository.

CREATE TABLE amministratore (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(255) NOT NULL UNIQUE,   -- UNIQUE: un solo admin per username
    password_hash VARCHAR(255) NOT NULL           -- la password CIFRATA (bcrypt, 60 caratteri), mai in chiaro
);

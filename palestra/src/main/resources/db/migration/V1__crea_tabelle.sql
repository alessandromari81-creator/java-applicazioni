-- FILE: V1__crea_tabelle.sql
-- A COSA SERVE: prima migration di Flyway: crea le tre tabelle dell'applicazione.
-- PARAGONE LARAVEL: un file in database/migrations (Schema::create...), ma scritto in SQL puro.
--
-- COME FUNZIONA FLYWAY: all'avvio dell'app guarda la cartella db/migration, ed esegue in ordine
-- di versione (V1, V2, V3...) i file che non ha ancora applicato, annotandoli nella tabella
-- flyway_schema_history (come la tabella "migrations" di Laravel). Un file GIÀ APPLICATO non si
-- modifica mai: Flyway ne controlla il checksum e rifiuta di partire se è cambiato.
-- Per cambiare lo schema si crea un NUOVO file (V3__..., V4__...).
-- Il nome è fisso: V<numero>__<descrizione>.sql (due underscore dopo il numero).

-- Corso (entità Corso). Le colonne devono corrispondere ai campi della classe:
-- Hibernate le verifica all'avvio (ddl-auto=validate) e se non coincidono l'app non parte.
CREATE TABLE corso (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- auto-increment
    nome          VARCHAR(255) NOT NULL,
    descrizione   VARCHAR(255),
    durata_minuti INTEGER      NOT NULL,   -- campo Java durataMinuti (camelCase -> snake_case)
    livello       VARCHAR(255)             -- l'enum Livello è salvato come testo
);

-- Utente (entità Utente).
CREATE TABLE utente (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome    VARCHAR(255) NOT NULL,
    cognome VARCHAR(255) NOT NULL,
    email   VARCHAR(255) NOT NULL UNIQUE   -- UNIQUE: niente due utenti con la stessa email
);

-- Tabella pivot many-to-many (come utente_corso in Laravel per belongsToMany).
-- La chiave primaria doppia impedisce di iscrivere due volte lo stesso utente allo stesso corso.
-- Le chiavi esterne impediscono di puntare a utenti o corsi che non esistono; senza ON DELETE
-- CASCADE il database rifiuta di eliminare un corso ancora usato (per questo CorsoService controlla prima).
CREATE TABLE utente_corso (
    utente_id BIGINT NOT NULL REFERENCES utente (id),
    corso_id  BIGINT NOT NULL REFERENCES corso (id),
    PRIMARY KEY (utente_id, corso_id)
);

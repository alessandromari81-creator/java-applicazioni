-- A COSA SERVE: quarta migration: unisce admin e iscritti in UN'UNICA tabella "utente" con più RUOLI per utente
-- (ADMIN, ISTRUTTORE, ISCRITTO). Prima c'era la tabella separata "amministratore" (V3), che qui viene eliminata.
-- PARAGONE LARAVEL: una tabella "users" + tabelle "roles" e "model_has_roles" (spatie/laravel-permission).
-- V1, V2 e V3 sono già applicate e non si modificano: si aggiunge questo NUOVO file che trasforma lo schema
-- E sposta i dati esistenti. È un esempio tipico di migration "con dati".

-- Tabella dei ruoli, con i tre ruoli iniziali. Il nome (ADMIN...) diventa l'autorità "ROLE_ADMIN" di Spring Security.
CREATE TABLE ruolo (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(50) NOT NULL UNIQUE
);
INSERT INTO ruolo (nome) VALUES ('ADMIN'), ('ISTRUTTORE'), ('ISCRITTO');

-- Password cifrata (hash bcrypt): può essere NULL, perché solo chi accede al pannello ha una password;
-- iscritti e istruttori sono anagrafiche senza login. Il login usa l'email come identificativo.
ALTER TABLE utente ADD COLUMN password_hash VARCHAR(255);

-- Pivot utente <-> ruolo (molti-a-molti: un utente può avere più ruoli).
CREATE TABLE utente_ruolo (
    utente_id BIGINT NOT NULL REFERENCES utente (id),
    ruolo_id  BIGINT NOT NULL REFERENCES ruolo (id),
    PRIMARY KEY (utente_id, ruolo_id)
);

-- 1) Gli utenti già presenti (Mario, Laura...) sono iscritti. ATTENZIONE ALL'ORDINE: va fatto PRIMA di
--    inserire gli admin qui sotto, altrimenti anche gli admin riceverebbero il ruolo ISCRITTO.
INSERT INTO utente_ruolo (utente_id, ruolo_id)
SELECT u.id, r.id FROM utente u, ruolo r WHERE r.nome = 'ISCRITTO';

-- 2) Gli amministratori della tabella vecchia diventano utenti con ruolo ADMIN, mantenendo la stessa password
--    (l'hash viene copiato, non si deve ricifrare nulla). Lo username non è un'email, quindi si ricava
--    "<username>@palestra.local": l'admin di sviluppo entra con admin@palestra.local.
INSERT INTO utente (nome, cognome, email, password_hash)
SELECT a.username, 'Amministratore', a.username || '@palestra.local', a.password_hash
FROM amministratore a;

INSERT INTO utente_ruolo (utente_id, ruolo_id)
SELECT u.id, r.id
FROM utente u
JOIN amministratore a ON u.email = a.username || '@palestra.local'
JOIN ruolo r ON r.nome = 'ADMIN';

-- 3) La tabella separata non serve più.
DROP TABLE amministratore;

-- A COSA SERVE: sesta migration: crea la tabella degli ABBONAMENTI degli iscritti.
-- Un utente ha MOLTI abbonamenti nel tempo (rinnovi): relazione uno-a-molti, con la chiave esterna utente_id.
-- La tabella resta vuota: gli abbonamenti si inseriscono dal pannello.

-- Estensione di PostgreSQL che serve al vincolo di non-sovrapposizione qui sotto (permette di usare "=" su
-- colonne normali dentro un indice di tipo GiST). Si installa una volta sola per database.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE abbonamento (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utente_id   BIGINT        NOT NULL REFERENCES utente (id),
    tipo        VARCHAR(20)   NOT NULL,           -- MENSILE, TRIMESTRALE, ANNUALE (testo, come l'enum Java)
    data_inizio DATE          NOT NULL,
    data_fine   DATE          NOT NULL,           -- calcolata dall'applicazione da data_inizio e tipo (INCLUSA)
    -- Prezzo in NUMERIC(8,2): numero decimale ESATTO, con 2 decimali e fino a 999999,99. Mai FLOAT/DOUBLE per i
    -- soldi: i decimali "approssimati" accumulano errori (0,1 + 0,2 non fa esattamente 0,3).
    -- Il prezzo è SALVATO sull'abbonamento (una "fotografia"): se il listino cambia, i vecchi abbonamenti no.
    prezzo      NUMERIC(8, 2) NOT NULL,

    -- Rete di sicurezza del database: la fine non può precedere l'inizio.
    CONSTRAINT chk_abbonamento_date CHECK (data_fine >= data_inizio),

    -- Rete di sicurezza contro le SOVRAPPOSIZIONI: lo stesso utente non può avere due abbonamenti con periodi che
    -- si incrociano. daterange(inizio, fine, '[]') è l'intervallo di date con estremi inclusi; "&&" significa
    -- "si sovrappone". Il controllo "gentile", con il messaggio per l'utente, lo fa già l'applicazione
    -- (AbbonamentoService); questo vincolo ferma comunque due richieste simultanee che passerebbero entrambe.
    CONSTRAINT abbonamento_senza_sovrapposizioni
        EXCLUDE USING gist (utente_id WITH =, daterange(data_inizio, data_fine, '[]') WITH &&)
);

-- Indice: rende veloci le ricerche "gli abbonamenti di questo utente".
CREATE INDEX idx_abbonamento_utente ON abbonamento (utente_id);

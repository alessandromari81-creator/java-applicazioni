-- V13: registrazioni di chi si è iscritto da solo ma NON ha ancora confermato l'email.
-- Chi compila il modulo di registrazione non diventa subito un utente: i suoi dati restano qui finché non clicca il link ricevuto per email e
-- sceglie la password; solo allora si crea la riga in "utente" e questa si cancella (quindi il link è monouso). Così la tabella "utente"
-- contiene solo persone vere e un indirizzo scritto male o di un altro non "occupa" l'email di nessuno.
--   email              sempre in minuscolo e UNICA: una sola registrazione in attesa per indirizzo (un nuovo invio sostituisce la precedente).
--   token_hash         hash SHA-256 del token del link (la stringa vera sta solo nell'email).
--   ultimo_invio_il    serve a non rispedire l'email più volte in pochi minuti.
--   scade_il           dopo questa data il link non vale più (24 ore); le righe scadute le cancella ogni notte la pulizia programmata.
-- Gli altri campi sono quelli del modulo (indirizzo, CAP, città) e i consensi dati al momento della registrazione.
CREATE TABLE registrazione_in_attesa (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                   VARCHAR(255)             NOT NULL UNIQUE CHECK (email = lower(email)),
    nome                    VARCHAR(255)             NOT NULL,
    cognome                 VARCHAR(255)             NOT NULL,
    indirizzo               VARCHAR(255)             NOT NULL,
    cap                     VARCHAR(10)              NOT NULL,
    citta                   VARCHAR(100)             NOT NULL,
    privacy_accettata_il    TIMESTAMP WITH TIME ZONE NOT NULL,
    privacy_versione        VARCHAR(20)              NOT NULL,
    consenso_marketing_il   TIMESTAMP WITH TIME ZONE,
    token_hash              VARCHAR(64)              NOT NULL UNIQUE,
    creato_il               TIMESTAMP WITH TIME ZONE NOT NULL,
    ultimo_invio_il         TIMESTAMP WITH TIME ZONE NOT NULL,
    scade_il                TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_registrazione_in_attesa_scadenza ON registrazione_in_attesa (scade_il);

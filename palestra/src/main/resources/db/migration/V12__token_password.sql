-- V12: token per impostare o reimpostare la password tramite il link ricevuto per email.
-- Come per i refresh token, nel database si salva solo l'HASH SHA-256 del token (la stringa vera sta solo nell'email), così chi
-- leggesse il database non troverebbe link utilizzabili.
--   tipo        RESET = "password dimenticata" (scade presto); ATTIVAZIONE = invito dell'amministratore a impostare la password.
--   scade_il    dopo questa data il link non vale più (1 ora per RESET, 24 ore per ATTIVAZIONE).
-- Il token è MONOUSO: quando si usa la riga viene cancellata. Per ogni utente e tipo ne esiste uno solo: una nuova richiesta
-- sostituisce la precedente (il vecchio link smette di funzionare).
-- ON DELETE CASCADE: eliminando l'utente spariscono anche i suoi token. I token scaduti li cancella ogni notte la pulizia programmata.
CREATE TABLE token_password (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utente_id   BIGINT                   NOT NULL REFERENCES utente (id) ON DELETE CASCADE,
    tipo        VARCHAR(20)              NOT NULL CHECK (tipo IN ('RESET', 'ATTIVAZIONE')),
    token_hash  VARCHAR(64)              NOT NULL UNIQUE,
    creato_il   TIMESTAMP WITH TIME ZONE NOT NULL,
    scade_il    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_token_password_utente ON token_password (utente_id);
CREATE INDEX idx_token_password_scadenza ON token_password (scade_il);
